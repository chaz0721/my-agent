# One-shot local install for daily use (Windows, PowerShell 5+).
#   powershell -NoProfile -ExecutionPolicy Bypass -File build\install.ps1
# What it does, all under your own account:
#   1. builds pai-cli.jar if missing (mvn -q package -DskipTests)
#   2. copies <repo>\.env to ~\.pai\.env if that file does not exist yet (keys are read from there in any directory)
#   3. writes a `pai` launcher to ~\.pai\bin (defaults to --provider deepseek unless you pass --provider)
#   4. adds ~\.pai\bin to your user PATH (skip with -NoPath)
# Nothing is printed from .env. Re-running is safe.
param([switch]$NoPath)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$jar = Join-Path $repo 'pai-cli\target\pai-cli.jar'
$home_ = [Environment]::GetFolderPath('UserProfile')
$paiHome = Join-Path $home_ '.pai'
$bin = Join-Path $paiHome 'bin'

if (-not (Test-Path $jar)) {
  Write-Host "building pai-cli.jar ..."
  Push-Location $repo
  try { & mvn -q package -DskipTests; if ($LASTEXITCODE -ne 0) { throw "mvn package failed" } } finally { Pop-Location }
}

New-Item -ItemType Directory -Force -Path $bin | Out-Null
$envSrc = Join-Path $repo '.env'; $envDst = Join-Path $paiHome '.env'
if ((Test-Path $envSrc) -and -not (Test-Path $envDst)) {
  Copy-Item $envSrc $envDst
  Write-Host "copied keys to $envDst (not shown)"
} elseif (Test-Path $envDst) {
  Write-Host "keys: $envDst already exists, left as is"
} else {
  Write-Host "no .env found; put PAI_OPENAI_COMPAT_API_KEY / PAI_OPENAI_COMPAT_BASE_URL in $envDst"
}

$cmd = @"
@echo off
rem pai launcher (generated by build\install.ps1). Default provider: deepseek.
setlocal
set "PAI_JAR=$jar"
if not exist "%PAI_JAR%" ( echo pai: %PAI_JAR% not found; run mvn -q package in $repo 1>&2 & exit /b 1 )
echo %* | findstr /C:"--provider" >nul
if errorlevel 1 ( set "PAI_DEFAULT=--provider deepseek" ) else ( set "PAI_DEFAULT=" )
java --enable-native-access=ALL-UNNAMED %PAI_JAVA_OPTS% -jar "%PAI_JAR%" %PAI_DEFAULT% %*
exit /b %ERRORLEVEL%
"@
Set-Content -Path (Join-Path $bin 'pai.cmd') -Value $cmd -Encoding ASCII
Write-Host "launcher: $bin\pai.cmd"

if (-not $NoPath) {
  $userPath = [Environment]::GetEnvironmentVariable('Path', 'User')
  if (($userPath -split ';') -notcontains $bin) {
    [Environment]::SetEnvironmentVariable('Path', ($userPath.TrimEnd(';') + ';' + $bin), 'User')
    Write-Host "added $bin to your user PATH (open a new terminal to pick it up)"
  } else { Write-Host "PATH already contains $bin" }
}
Write-Host ""
Write-Host "done. In a NEW terminal:  cd <your project>  then  pai"
Write-Host "  pai --help        options;  inside pai: /help, Shift+Tab switches ask / auto-read / plan"
